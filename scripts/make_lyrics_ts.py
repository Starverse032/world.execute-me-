# Sung lines for the lyric guard (src/v4/lyrics.ts) from docs/lyrics.lrc.
# An ALL-CAPS LRC line is a keyword: it joins the lead-in before it, as in the subtitles.
# usage: python scripts/make_lyrics_ts.py
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for line in (root / 'docs' / 'lyrics.lrc').read_text(encoding='utf-8').splitlines():
    m = re.match(r'\[(\d+):(\d+\.\d+)\](.*)', line)
    if m:
        t = int(m.group(1)) * 60 + float(m.group(2))
        en = m.group(3).strip().replace("'", '’')
        kw = en.isupper() and len(en) > 1 and not en.startswith('WORLD')
        rows.append([t, en, kw])
lines = []
for i, (t, en, kw) in enumerate(rows):
    nxt = rows[i + 1][0] if i + 1 < len(rows) else t + 4
    if kw and lines and abs(lines[-1]['end'] - t) < 0.05:
        lines[-1]['text'] += ' ' + en
        lines[-1]['end'] = min(nxt, t + 4)
    else:
        lines.append({'t': round(t, 3), 'end': round(min(nxt, t + 4), 3), 'text': en})
out = '// Generated by scripts/make_lyrics_ts.py from docs/lyrics.lrc: each sung line\n// with its start and end (song seconds). Used by the lyric guard.\n'
out += 'export const LYRICS: {t: number; end: number; text: string}[] = ' + json.dumps(lines, ensure_ascii=False, indent=1) + ';\n'
(root / 'src' / 'v4' / 'lyrics.ts').write_text(out, encoding='utf-8')
print(len(lines), 'lines')
